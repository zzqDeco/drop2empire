#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT_DIR}"

# 1. Contract sync gate
make gen
git diff --exit-code -- contracts/ packages/api-client/src/generated.ts

# 2. Generated code purity gate: every .go file in contracts/gen/ must be tool-generated
while IFS= read -r -d '' f; do
  if ! head -n 1 "${f}" | grep -q '^// Code generated by '; then
    echo "Handwritten .go file found in contracts/gen/: ${f}" >&2
    exit 1
  fi
done < <(find contracts/gen -type f -name '*.go' -print0)

# 3. DDD domain layer purity gate: services/*/internal/domain/... must never import hertz, kitex, pgx, contracts/gen, or drop2empire/
for svc in services/*; do
  if [[ -d "${svc}/internal/domain" ]]; then
    domain_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/domain/...)"
    if printf '%s\n' "${domain_imports}" | grep -E '(hertz|kitex|pgx|contracts/gen|drop2empire/)' >/dev/null; then
      echo "DDD domain layer purity violation in ${svc}/internal/domain" >&2
      exit 1
    fi
  fi
done

# 4. DDD app layer purity gate: services/*/internal/app/... must never import adapter, infra, hertz, kitex, pgx, or contracts/gen
for svc in services/*; do
  if [[ -d "${svc}/internal/app" ]]; then
    app_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/app/...)"
    if printf '%s\n' "${app_imports}" | grep -E '(internal/adapter|internal/infra|hertz|kitex|pgx|contracts/gen)' >/dev/null; then
      echo "DDD app layer purity violation in ${svc}/internal/app" >&2
      exit 1
    fi
  fi
done

# 5. Unified PostgreSQL mechanism gate: every service with internal/infra/pg must import drop2empire/pkg/postgres
for svc in services/*; do
  if [[ -d "${svc}/internal/infra/pg" ]]; then
    pg_imports="$(cd "${svc}" && go list -f '{{join .Imports "\n"}}' ./internal/infra/pg/...)"
    if ! printf '%s\n' "${pg_imports}" | grep -Fx 'drop2empire/pkg/postgres' >/dev/null; then
      echo "infra/pg in ${svc} must use shared drop2empire/pkg/postgres mechanism" >&2
      exit 1
    fi
  fi
done

# 6. Modular governance & 4D game design documentation gate
required_docs=(
  "AGENTS.md"
  "CONTRIBUTING.md"
  "README.md"
  "docs/README.md"
  "docs/architecture/overview.md"
  "docs/architecture/ddd-idl.md"
  "docs/contracts/http-v1.md"
  "docs/design/01-overall/vision-and-pillars.md"
  "docs/design/01-overall/lifecycle-and-loops.md"
  "docs/design/02-macro/monetary-and-clob-market.md"
  "docs/design/02-macro/profession-and-economy-boundary.md"
  "docs/design/02-macro/chamber-war-macro.md"
  "docs/design/03-micro/settlement-production-and-edicts.md"
  "docs/design/03-micro/wasteland-2d-extraction-roguelite.md"
  "docs/design/03-micro/avatar-and-procedural-relics.md"
  "docs/design/04-seasons/season-framework.md"
  "docs/design/04-seasons/s1-obsidian-awakening.md"
)
for doc in "${required_docs[@]}"; do
  if [[ ! -f "${doc}" ]]; then
    echo "Missing required modular governance/design document: ${doc}" >&2
    exit 1
  fi
done
if compgen -G "docs/gdd-*.md" >/dev/null; then
  echo "Monolithic docs/gdd-*.md files are forbidden; place specs in docs/design/{01-overall,02-macro,03-micro,04-seasons}/" >&2
  exit 1
fi
